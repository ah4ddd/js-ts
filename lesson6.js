// Loops

// Part 1 — Initialization -> let i = 0 . Create i and start at 0.

// Part 2 — Condition -> i < 5 Before every iteration,
// JavaScript asks: Is this still true?

// Part 3 — Update -> i++
// After each iteration: Increase i by 1.


for (let i = 0; i < 6; i++) {
    console.log(i)
}

for (let i = 4; i >= 0; i--) {
    console.log(i)
}



